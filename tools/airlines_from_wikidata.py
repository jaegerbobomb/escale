"""Build the airline IATA -> ICAO table from Wikidata (S016).

Wikidata's data is CC0, so the table can ship with a GPL app. Run it again to refresh:

    uv run python tools/airlines_from_wikidata.py

Rules, so that a doubtful code gives no link rather than a wrong one:

- only airlines with no dissolution date (P576), and only IATA (P229) and ICAO (P230)
  statements of best rank with no end date;
- several airlines sharing an IATA code: the one with at least twice the Wikipedia
  articles (sitelinks) of the next is kept (Lufthansa over Lufthansa Cargo); otherwise
  the code is left out.
"""

from __future__ import annotations

import csv
import io
import re
import urllib.parse
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "packages" / "escale-core" / "src" / "escale_core" / "data" / "airlines.csv"
ENDPOINT = "https://query.wikidata.org/sparql"
QUERY = """
SELECT ?item ?iata ?icao ?links WHERE {
  ?item p:P229 ?a . ?a ps:P229 ?iata ; a wikibase:BestRank . FILTER NOT EXISTS { ?a pq:P582 [] }
  ?item p:P230 ?b . ?b ps:P230 ?icao ; a wikibase:BestRank . FILTER NOT EXISTS { ?b pq:P582 [] }
  FILTER NOT EXISTS { ?item wdt:P576 [] }
  ?item wikibase:sitelinks ?links .
}
"""
DOMINANCE = 2


def fetch() -> list[dict[str, str]]:
    url = ENDPOINT + "?" + urllib.parse.urlencode({"query": QUERY})
    request = urllib.request.Request(
        url, headers={"Accept": "text/csv", "User-Agent": "escale-build/1.0 (airline table)"}
    )
    with urllib.request.urlopen(request, timeout=120) as response:
        return list(csv.DictReader(io.StringIO(response.read().decode())))


def resolve(rows: list[dict[str, str]]) -> dict[str, str]:
    """IATA code -> ICAO code, for the codes that are not in doubt."""
    links: dict[str, dict[str, int]] = defaultdict(dict)
    for row in rows:
        iata, icao = row["iata"], row["icao"]
        if re.fullmatch(r"[A-Z0-9]{2}", iata) and re.fullmatch(r"[A-Z]{3}", icao):
            links[iata][icao] = max(int(row["links"]), links[iata].get(icao, 0))
    table: dict[str, str] = {}
    for iata, candidates in links.items():
        ranked = sorted(candidates.items(), key=lambda kv: (-kv[1], kv[0]))
        if len(ranked) == 1 or ranked[0][1] >= DOMINANCE * max(ranked[1][1], 1):
            table[iata] = ranked[0][0]
    return dict(sorted(table.items()))


def main() -> int:
    table = resolve(fetch())
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", newline="") as f:
        f.write("# Airline IATA -> ICAO designators, from Wikidata (CC0).\n")
        f.write("# Generated by tools/airlines_from_wikidata.py; do not edit by hand.\n")
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(["iata", "icao"])
        writer.writerows(table.items())
    print(f"{len(table)} airlines -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
